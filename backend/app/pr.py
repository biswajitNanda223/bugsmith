"""Milestone 6: turn a validated fix into a draft pull request.

Safe by default: `preview()` never touches the network. `open_draft_pr()` pushes a new branch
(never the base branch) and opens a DRAFT PR; it needs GITHUB_TOKEN + BUGSMITH_GITHUB_REPO and is only
called when a person clicks "Open draft PR" (or BUGSMITH_AUTO_PR=1).
"""
import base64
import os
import re
import subprocess
import tempfile
from pathlib import Path

import httpx


def branch_name(issue_id: str) -> str:
    return "bugsmith/" + re.sub(r"[^A-Za-z0-9._-]+", "-", issue_id).strip("-").lower()


def repro_path(fix: dict, issue_id: str) -> str:
    slug = re.sub(r"[^a-z0-9]+", "_", issue_id.lower()).strip("_")
    return str(Path(fix.get("workdir", ".")) / "tests" / f"test_bugsmith_{slug}.py")


def preview(run: dict, incident: dict) -> dict:
    rca, fix, val = run["rca"], run["fix"], run["validation"]
    b = rca["confidence_breakdown"]
    steps = "\n".join(f"- {'✅' if s['ok'] else '❌'} `{s['name']}`" for s in val["steps"])
    evidence = "\n".join(f"- {e}" for e in rca["evidence"])
    body = f"""## Root cause
{rca['summary']}

`{rca['faulty_file']}:{rca['faulty_lines']}` — {rca['hypothesis']}

## Evidence
{evidence}

## Fix
{fix['explanation']}

## Validation (sandbox, attempt {val['attempt']})
{steps}

A reproduction test (`{repro_path(fix, incident['issue_id'])}`) fails before the patch and passes after it.

## Confidence
**{b['final']:.0%}** — {', '.join(f"{a} {v:.0%}" for a, v in b['agents'].items())}.
Based on {b['similar_incidents']} similar past incident(s).

> Generated by BugSmith from crash `{incident['issue_id']}` ({incident['title']}). Draft — a human must review before merging.
"""
    return {"title": f"fix: {rca['summary']}"[:120], "body": body, "branch": branch_name(incident["issue_id"]),
            "patch": fix["patch"], "repro_test_path": repro_path(fix, incident["issue_id"]), "draft": True}


def _git(args: list[str], cwd: Path, token: str = "") -> str:
    cmd = ["git"]
    if token:  # keep the token out of URLs and process lists' remote output
        auth = base64.b64encode(f"x-access-token:{token}".encode()).decode()
        cmd += ["-c", f"http.extraheader=Authorization: Basic {auth}"]
    p = subprocess.run(cmd + args, cwd=cwd, capture_output=True, text=True, timeout=120,
                       env={**os.environ, "GIT_TERMINAL_PROMPT": "0"})
    if p.returncode:
        raise RuntimeError(f"git {args[0]} failed: {p.stderr.strip()[-400:].replace(token, '***') if token else p.stderr.strip()[-400:]}")
    return p.stdout


def open_draft_pr(pv: dict, fix: dict, *, repo: str, base: str = "main", token: str = "",
                  remote_url: str | None = None, api=None) -> dict:
    """Push pv['branch'] with the patch + repro test, then open a draft PR. `api(payload)->dict` is injectable for tests."""
    if pv["branch"] in {base, "main", "master"}:
        raise ValueError("refusing to push to a protected branch name")
    url = remote_url or f"https://github.com/{repo}.git"
    with tempfile.TemporaryDirectory(prefix="bugsmith-pr-") as tmp:
        work = Path(tmp) / "clone"
        _git(["clone", "--depth", "1", "--branch", base, url, str(work)], Path(tmp), token)
        _git(["checkout", "-b", pv["branch"]], work)
        (work / "_fix.patch").write_text(pv["patch"])
        _git(["apply", "--whitespace=nowarn", "_fix.patch"], work)
        (work / "_fix.patch").unlink()
        test = work / pv["repro_test_path"]
        test.parent.mkdir(parents=True, exist_ok=True)
        test.write_text(fix["repro_test"])
        _git(["add", "-A"], work)
        _git(["-c", "user.name=BugSmith", "-c", "user.email=bugsmith@users.noreply.github.com",
              "commit", "-m", pv["title"] + "\n\nGenerated by BugSmith. See PR description."], work)
        _git(["push", "origin", pv["branch"]], work, token)
    payload = {"title": pv["title"], "body": pv["body"], "head": pv["branch"], "base": base, "draft": True}
    if api:
        return api(payload)
    r = httpx.post(f"https://api.github.com/repos/{repo}/pulls", json=payload, timeout=30,
                   headers={"Authorization": f"Bearer {token}", "Accept": "application/vnd.github+json"})
    r.raise_for_status()
    return {"url": r.json()["html_url"], "number": r.json()["number"]}
